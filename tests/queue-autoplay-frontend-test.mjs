import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (file) => readFileSync(new URL("../" + file, import.meta.url), "utf8");
const hook = read("app/components/use-playback-queue.ts");
const panel = read("app/components/QueuePanel.tsx");
const page = read("app/page.tsx");
const topbar = read("app/components/TopBar.tsx");
const watch = read("app/components/WatchView.tsx");
for (const action of ["enqueue", "remove", "reorder", "clear", "current", "autoplay", "next", "ended"]) assert.match(hook, new RegExp('"' + action + '"'));
assert.match(panel, /draggable/);
assert.match(panel, /queue-drag-handle/);
assert.match(panel, /ArrowUp/);
assert.match(panel, /Remove .* from the queue/);
assert.match(panel, /Clear queue/);
assert.match(panel, /Autoplay is off/);
assert.match(page, /queueOpen/);
assert.match(page, /global-queue/);
assert.match(page, /wasEmpty/);
assert.match(topbar, /queueCount/);
assert.match(topbar, /onToggleQueue/);
assert.doesNotMatch(watch, /<QueuePanel/);
assert.match(watch, /Recommended/);
assert.match(page, /queue\.resolveEnded\(\)/);
console.log("queue drawer frontend tests passed");
