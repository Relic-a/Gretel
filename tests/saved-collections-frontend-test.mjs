import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (file) => readFileSync(new URL("../" + file, import.meta.url), "utf8");
const workspace = read("app/components/SavedWorkspace.tsx");
const hook = read("app/components/use-saved-collections.tsx");
const page = read("app/page.tsx");
for (const token of ["All saved", "New collection", "Advanced filters", "Organize", "Add note"]) assert.match(workspace, new RegExp(token));
assert.match(workspace, /maxLength=\{5000\}/);
assert.match(workspace, /aria-label="Saved collections"/);
assert.match(workspace, /role="dialog"/);
assert.match(workspace, /aria-modal="true"/);
assert.match(workspace, /saved-card-more/);
assert.match(workspace, /saved-collection-label/);
assert.doesNotMatch(workspace, /<h2>Tags<\/h2>/);
assert.doesNotMatch(workspace, /placeholder="New tag"/);
for (const action of ["save", "unsave", "update-item", "create-folder", "rename-folder", "delete-folder"]) assert.match(hook + page, new RegExp('"' + action + '"'));
assert.match(page, /showSaveNotice/);
assert.match(page, /Organize/);
console.log("saved collection simplification frontend tests passed");
